// Learns digit templates for src/data/team-screens.js from a stats-screen screenshot whose
// numbers are known (test/fixtures/team-screens). Writes src/data/team-screens-digits.js.
//
// Usage: node scripts/learn-team-screen-digits.mjs [stats.png] [truth.json]
import { readFileSync, writeFileSync } from "node:fs";
import { decodePng } from "./png.mjs";
import { PANELS, splitGlyphs, statCellBoxes, textMask, maskVector } from "../src/data/team-screens.js";
import { DIGIT_GRID } from "../src/data/team-screens-digits.js";

const [pngPath = "test/fixtures/team-screens/stats.png", truthPath = "test/fixtures/team-screens/truth.json"] = process.argv.slice(2);
const image = decodePng(pngPath);
const truth = JSON.parse(readFileSync(truthPath, "utf8")).team;
const sums = {};
PANELS.forEach((panel, slot) => {
  const member = truth[slot];
  statCellBoxes(panel).forEach(({ index, valueBox, spBox }) => {
    for (const [box, value] of [[valueBox, member.stats[index]], [spBox, member.sp[index]]]) {
      const mask = textMask(image, box);
      const glyphs = splitGlyphs(mask).filter((g) => g.height > mask.height * 0.5);
      const digits = String(value);
      if (glyphs.length !== digits.length) throw new Error(`Slot ${slot} stat ${index}: ${glyphs.length} glyphs for ${digits}`);
      glyphs.forEach((glyph, i) => {
        const v = maskVector(glyph, DIGIT_GRID.width, DIGIT_GRID.height);
        const s = (sums[digits[i]] ??= new Float64Array(v.length));
        for (let k = 0; k < v.length; k++) s[k] += v[k];
      });
    }
  });
});
const templates = {};
for (const digit of Object.keys(sums).sort()) {
  const s = sums[digit];
  const norm = Math.hypot(...s) || 1;
  templates[digit] = [...s].map((x) => Math.round((x / norm) * 1000) / 1000);
}
const missing = "0123456789".split("").filter((d) => !templates[d]);
if (missing.length) throw new Error(`No samples for digits ${missing.join(", ")}`);
writeFileSync(
  "src/data/team-screens-digits.js",
  `// Generated by scripts/learn-team-screen-digits.mjs from test/fixtures/team-screens/stats.png.\n` +
    `// Unit-length glyph vectors of the game's digits on a ${DIGIT_GRID.width}×${DIGIT_GRID.height} grid.\n` +
    `export const DIGIT_GRID = ${JSON.stringify(DIGIT_GRID)};\n` +
    `export const DIGIT_TEMPLATES = {\n${Object.entries(templates).map(([d, v]) => `  ${d}: [${v.join(", ")}],`).join("\n")}\n};\n`,
);
console.log(`Learned ${Object.keys(templates).length} digits.`);
